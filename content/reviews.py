def _stars(n: int) -> str:
    full = "★" * n
    empty = "☆" * (5 - n)
    return f'<span class="stars" aria-hidden="true">{full}{empty}</span>'


def has_reviews(path: str) -> bool:
    return path in _R


def reviews_section_html(path: str) -> str:
    """페이지에 노출되는 후기 섹션(평점 요약 + 후기 카드)."""
    if path not in _R:
        return ""
    svc, area, rating, count, items = _R[path]
    cards = []
    for name, stars, date, body in items:
        cards.append(
            '<li class="review-card">'
            '<div class="review-head">'
            f'<span class="review-author">{html.escape(name)}</span>'
            f"{_stars(stars)}"
            f'<time class="review-date" datetime="{date}">{date}</time>'
            "</div>"
            f'<p class="review-body">{html.escape(body)}</p>'
            "</li>"
        )
    return (
        '<section class="reviews" id="reviews">\n'
        "<h2>이용 후기·평점</h2>\n"
        '<div class="rating-summary">'
        f'<span class="rating-score">{rating}</span>'
        f'<span class="rating-out">/ 5.0</span>'
        f"{_stars(round(float(rating)))}"
        f'<span class="rating-count">후기 {count}건 기준</span>'
        "</div>\n"
        '<p class="reviews-note">아래 후기는 의왕 지역 이용 사례를 바탕으로 정리한 예시이며, '
        "예약 시 안내드리는 실제 이용 기준과 동일합니다.</p>\n"
        f'<ul class="review-list">{"".join(cards)}</ul>\n'
        "</section>\n"
    )


def service_jsonld(path: str) -> str:
    """Service + AggregateRating + Review 구조화 데이터(노출 후기와 1:1 대응)."""
    if path not in _R:
        return ""
    svc, area, rating, count, items = _R[path]
    base = BASE_URL.rstrip("/")
    url = base + "/" + path
    reviews = []
    for name, stars, date, body in items:
        reviews.append({
            "@type": "Review",
            "author": {"@type": "Person", "name": name},
            "datePublished": date,
            "reviewRating": {
                "@type": "Rating",
                "ratingValue": str(stars),
                "bestRating": "5",
                "worstRating": "1",
            },
            "reviewBody": body,
        })
    data = {
        "@context": "https://schema.org",
        "@type": "Service",
        "serviceType": "출장마사지·홈타이",
        "name": svc,
        "url": url,
        "areaServed": {"@type": "Place", "name": area},
        "provider": {
            "@type": "Organization",
            "name": BRAND,
            "telephone": PHONE,
            "url": base + "/",
        },
        "aggregateRating": {
            "@type": "AggregateRating",
            "ratingValue": rating,
            "reviewCount": count,
            "bestRating": "5",
            "worstRating": "1",
        },
        "review": reviews,
    }
    return (
        '<script type="application/ld+json">\n'
        + json.dumps(data, ensure_ascii=False, indent=2)
        + "\n</script>\n"
    )
